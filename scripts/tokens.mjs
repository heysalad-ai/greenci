import { format } from 'prettier';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const source = JSON.parse(
  readFileSync(new URL('design-system/tokens.json', root), 'utf8'),
);
// Keep the supplied CSS byte-identical, alongside a literal typed TS export.
mkdirSync(new URL('packages/tokens/generated/', root), { recursive: true });
writeFileSync(
  new URL('packages/tokens/src/index.ts', root),
  await format(
    `// Generated by scripts/tokens.mjs from design-system/tokens.json.\nexport const tokens = ${JSON.stringify(source, null, 2)} as const;\nexport type Theme = typeof tokens.color.themes[number]['id'];\n`,
    { parser: 'typescript', singleQuote: true },
  ),
);
copyFileSync(
  new URL('design-system/tokens.css', root),
  new URL('packages/tokens/generated/tokens.css', root),
);
